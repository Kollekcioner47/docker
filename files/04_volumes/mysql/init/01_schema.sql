-- Начальная схема для практики 4.
--
-- Этот файл образ MySQL выполняет РОВНО ОДИН РАЗ: при первой
-- инициализации, то есть когда каталог данных /var/lib/mysql пуст.
-- Отсюда два вывода, которые проверяются в практике:
--
--   1. когда мы запускаем новый контейнер с тем же томом, каталог
--      данных не пуст, и этот скрипт не выполняется: сервер просто
--      подключается к существующим данным;
--   2. чтобы применить правку в этом файле, нужен либо новый том,
--      либо ручное выполнение SQL. Иначе изменения никто не заметит,
--      и это выглядит как «файл поправил, а ничего не произошло».

CREATE DATABASE IF NOT EXISTS notes;

USE notes;

CREATE TABLE IF NOT EXISTS notes (
    id         INT AUTO_INCREMENT PRIMARY KEY,
    body       VARCHAR(200) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Текст записей здесь латиницей намеренно: клиент mysql в табличном
-- выводе считает ширину колонки по числу байт, а кириллическая буква
-- занимает два байта, поэтому строки в таблице разъезжаются. К данным
-- это отношения не имеет, но читать мешает.
INSERT INTO notes (body) VALUES ('row created by the init script');
